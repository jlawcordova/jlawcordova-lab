// Writes docs/cli.md from the command registry, so the command list never
// drifts from the code: `npm run docs:cli`. With --check it only compares,
// and exits 1 if docs/cli.md is out of date (the tests run that).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { commandWords, GLOBAL_FLAGS, kebab } from '../cli/lib/argv.mjs';
import { usageLine } from '../cli/lib/help.mjs';
import { registry } from '../cli/lib/registry.mjs';
import { LEFT_OUT, PROTOCOL_VERSION as MCP_VERSION, toolName } from '../cli/lib/server-mcp.mjs';
import { PROTOCOL_VERSION } from '../cli/lib/server-stdio.mjs';

const FILE = fileURLToPath(new URL('../docs/cli.md', import.meta.url));
const REPO = '/Users/jlawcordova/Projects/jlawcordova-lab';

const cell = (/** @type {string} */ s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function typeOf(/** @type {any} */ s) {
  if (s.enum) return s.enum.map((/** @type {unknown} */ v) => `\`${v}\``).join(' \\| ');
  if (s.type === 'array') return s.items?.type === 'array' ? `list of [${s.items.items?.type ?? 'value'}, …]` : `list of ${s.items?.type ?? 'values'}`;
  return s.type ?? 'any';
}

function commandSection(/** @type {import('../cli/lib/registry.mjs').Command} */ cmd) {
  const props = Object.entries(cmd.params.properties ?? {});
  const required = new Set(cmd.params.required ?? []);
  const facts = [
    cmd.mutates ? 'edits docs' : 'read-only',
    cmd.session ? 'session only (`serve`)' : '',
    cmd.writes ? 'writes files directly' : '',
    cmd.name in LEFT_OUT ? 'not an MCP tool' : `MCP tool \`${toolName(cmd.name)}\``,
  ].filter(Boolean);
  const lines = [`#### ${cmd.name}`, '', `${cmd.summary}.`, '', '```', usageLine(cmd), '```', ''];
  if (cmd.description) lines.push(cmd.description, '');
  lines.push(facts.join(' · '), '');
  if (props.length) {
    lines.push('| param | type | | description |', '| --- | --- | --- | --- |');
    for (const [key, schema] of props) {
      const s = /** @type {any} */ (schema);
      const req = required.has(key) ? 'required' : s.default !== undefined ? `default \`${JSON.stringify(s.default)}\`` : '';
      const range = s.minimum !== undefined && s.maximum !== undefined ? ` (${s.minimum} to ${s.maximum})` : s.minimum !== undefined ? ` (at least ${s.minimum})` : '';
      const flag = (cmd.args ?? []).includes(key) ? `\`${key}\` (positional)` : `\`--${kebab(key)}\``;
      lines.push(`| ${flag} | ${typeOf(s)} | ${req} | ${cell((s.description ?? '') + range)} |`);
    }
    lines.push('');
  }
  if (cmd.examples?.length) lines.push('```sh', ...cmd.examples, '```', '');
  return lines.join('\n');
}

